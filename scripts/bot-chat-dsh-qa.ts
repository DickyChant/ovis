// Opt-in check against an already bootstrapped DS Bot mock bench, never a user's DSH.
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { basename, join } from "node:path";
import { tmpdir } from "node:os";
import { chromium } from "playwright-core";
import "./test-herdr.ts";
import { createServer } from "../server/index.ts";
import { BotsService } from "../server/bots.ts";
import { BotChatService } from "../server/bot-chat.ts";

const home = process.env["BOT_CHAT_TEST_HOME"] ?? "";
const port = Number(process.env["BOT_CHAT_TEST_PORT"]);
assert.match(basename(home), /^\.dsh-test-[a-z0-9-]+$/);
assert.ok(Number.isInteger(port) && port > 1024 && port !== 3080);
const url = `http://127.0.0.1:${port}`;
const token = readFileSync(join(home, "bridge-token"), "utf8").trim();
const bots = new BotsService({ url });
const directory = await bots.snapshot();
assert.equal(directory.state, "online");
assert.equal(directory.runtimeId, readFileSync(join(home, "bot", "directory-id"), "utf8").trim());
const chief = directory.bots.find((bot) => bot.name === "Chief")!;
assert.ok(chief);
const stateDir = mkdtempSync(join(tmpdir(), "ovis-dsh-chat-"));
const server = createServer({ port: 0, hostname: "127.0.0.1", stateDir, token: "", tailscaleOwner: null, bots, botChat: new BotChatService({ url, token }) });
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, locale: "en-US" });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.port}`);
  await page.getByRole("link", { name: "Bots", exact: true }).click();
  const dialog = page.getByRole("main", { name: "DSH workspace", exact: true });
  await dialog.locator(".bots-row").filter({ hasText: "Chief" }).click();
  await dialog.getByText("Connected to DSH", { exact: true }).waitFor();
  const input = dialog.getByRole("textbox", { name: "Message Chief" });
  const prompt = `慢慢说 Ovis bridge fixture ${crypto.randomUUID()}`;
  const completed = dialog.locator(".bot-chat-message:not(.is-streaming)").filter({ hasText: "好，我一点一点说" });
  const before = await completed.count();
  await input.fill(prompt);
  await dialog.getByRole("button", { name: "Send message", exact: true }).click();
  await dialog.locator(".is-streaming").filter({ hasText: "好，我" }).waitFor({ timeout: 30000 });
  await completed.nth(before).waitFor({ timeout: 30000 });
  assert.equal(await input.inputValue(), "");
  const userMessage = dialog.locator(".bot-chat-message.is-user").filter({ hasText: prompt });
  assert.equal(await userMessage.count(), 1);
  const base = `http://127.0.0.1:${server.port}`;
  const response = await fetch(`${base}/api/bots/chat?${new URLSearchParams({ runtimeId: directory.runtimeId!, botId: chief.id })}`);
  assert.equal(response.status, 200);
  const settingsResponse = await fetch(`${base}/api/bots/settings?${new URLSearchParams({ runtimeId: directory.runtimeId!, botId: chief.id })}`);
  assert.equal(settingsResponse.status, 200);
  const settings = await settingsResponse.json() as { model: string; models: { ref: string; available: boolean }[] };
  const nextModel = settings.models.find((entry) => entry.available && entry.ref !== settings.model);
  assert.ok(nextModel, "mock bench offers a second model");
  await dialog.getByRole("combobox", { name: "Bot model" }).selectOption(nextModel.ref);
  await dialog.getByRole("button", { name: "Apply model" }).click();
  await page.waitForResponse(async (response) => response.url().includes("/api/bots/settings") && response.ok() && (await response.json()).model === nextModel.ref);
  await input.fill(`慢慢说 Ovis stop fixture ${crypto.randomUUID()}`);
  await dialog.getByRole("button", { name: "Send message", exact: true }).click();
  await dialog.locator(".is-streaming").first().waitFor({ timeout: 30000 });
  const stop = dialog.getByRole("button", { name: "Stop reply", exact: true });
  await stop.click({ timeout: 30000 });
  await dialog.locator(".is-streaming").waitFor({ state: "detached", timeout: 30000 });
  const fileName = `fixture-${crypto.randomUUID()}.txt`;
  const uploadResponse = page.waitForResponse((response) => response.url().endsWith('/api/bots/upload'));
  await dialog.locator('input[type="file"]').setInputFiles({ name: fileName, mimeType: "text/plain", buffer: Buffer.from("Fictional attachment 你好") });
  assert.equal((await uploadResponse).status(), 200, "native upload succeeds");
  await dialog.locator(".bot-chat-composer").getByText(fileName).waitFor();
  console.log("PASS native upload");
  await input.fill("Read the attached fixture");
  await dialog.getByRole("button", { name: "Send message", exact: true }).click();
  const fileLink = dialog.locator(".bot-chat-history a").filter({ hasText: fileName });
  await fileLink.waitFor({ timeout: 30000 });
  const download = await page.request.get(new URL((await fileLink.getAttribute("href"))!, base).href);
  assert.equal(download.status(), 200); assert.equal(await download.text(), "Fictional attachment 你好");
  assert.match(download.headers()["content-disposition"]!, /^attachment;/);
  await input.fill("Ovis approval fixture");
  await dialog.getByRole("button", { name: "Send message", exact: true }).click();
  await dialog.getByRole("button", { name: "Reject", exact: true }).click({ timeout: 30000 });
  await dialog.locator(".bot-approval").waitFor({ state: "detached", timeout: 30000 });
  console.log("PASS native direct approval rejection and download");
  const group = chief.conversations.find((entry) => entry.kind === "group");
  assert.ok(group, "fixture contains a group shared by Chief and Coder");
  await dialog.getByRole("combobox", { name: "Conversations", exact: true }).selectOption(group.id);
  await dialog.getByText("Connected to DSH", { exact: true }).waitFor();
  assert.equal(await dialog.getByRole("button", { name: "Stop reply", exact: true }).count(), 0, "a group never stops the Bot's direct session");
  const groupInput = dialog.getByRole("textbox", { name: `Message ${group.name}` });
  const groupPrompt = `@Coder native group fixture ${crypto.randomUUID()}`;
  await groupInput.fill(groupPrompt);
  await dialog.getByRole("button", { name: "Send message", exact: true }).click();
  await dialog.locator(".bot-chat-message.is-user").filter({ hasText: groupPrompt }).waitFor({ timeout: 30000 });
  await groupInput.fill("@Coder 提权");
  await dialog.getByRole("button", { name: "Send message", exact: true }).click();
  await dialog.getByRole("button", { name: "Reject", exact: true }).click({ timeout: 30000 });
  await dialog.locator(".bot-approval").waitFor({ state: "detached", timeout: 30000 });
  await dialog.getByRole("combobox", { name: "Conversations", exact: true }).selectOption("");
  assert.equal(await dialog.locator(".bot-chat-message").filter({ hasText: groupPrompt }).count(), 0, "group text stays out of the direct chat");
  assert.equal(await page.locator("iframe").count(), 0);
  assert.equal((await page.context().cookies(url)).filter((cookie) => cookie.name.startsWith("dsh")).length, 0, "native controls and chat need no DSH browser session");
  await dialog.getByRole("button", { name: "Back to terminals", exact: true }).click();
  const login = readFileSync(join(home, "web.log"), "utf8").match(new RegExp(`http://127\\.0\\.0\\.1:${port}/\\?token=[^\\s]+`))?.[0];
  assert.ok(login);
  await page.context().request.get(login);
  await page.getByRole("button", { name: "Open DSH", exact: true }).click();
  const portal = page.getByRole("dialog", { name: "DSH workspace", exact: true });
  const frame = portal.frameLocator("iframe");
  await frame.locator("[data-bot-id]").first().waitFor({ timeout: 30000 });
  assert.equal(await portal.locator("iframe").getAttribute("src"), `${url}/`);
  await portal.getByRole("button", { name: "Close DSH" }).click();
  assert.deepEqual(errors, []);
  console.log("PASS real DSH: native history, queued send, streaming, persisted reply, model selection, stop, file upload/download, direct and group approval rejection and group sends without a DSH browser login; original portal still works");
} finally { await browser.close(); server.stop(); rmSync(stateDir, { recursive: true, force: true }); }
